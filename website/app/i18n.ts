export type Locale = keyof typeof translations

export function normalizeLocale(value: string | string[] | null | undefined): Locale | null {
  const candidate = Array.isArray(value) ? value[0] : value

  if (!candidate) return null

  const normalized = candidate.toLowerCase()
  if (normalized.startsWith('pt')) return 'pt'
  if (normalized.startsWith('es')) return 'es'
  if (normalized.startsWith('en')) return 'en'

  return null
}

export function detectLocale(acceptLanguage: string | null): Locale {
  if (!acceptLanguage) return 'en'

  for (const language of acceptLanguage.split(',')) {
    const locale = normalizeLocale(language.trim().split(';')[0])
    if (locale) return locale
  }

  return 'en'
}

export function resolveLocale(preferredLocale: string | undefined, acceptLanguage: string | null): Locale {
  return normalizeLocale(preferredLocale) ?? detectLocale(acceptLanguage)
}

export function getTranslation(locale: Locale) {
  return translations[locale]
}
